# ============================================================
# 业务逻辑层（service 层）：项目的"业务心脏"
# ============================================================
# 调用链：routers(接口层) -> services(本层) -> crud(数据访问层) -> models(ORM)
#
# 本层职责：
# 1. 流程编排：把一个业务动作拆解为多步操作并按顺序执行
#    例：注册 = 查重 -> 密码加密 -> 创建用户 -> 签发 token
#    例：新闻详情 = 查详情 -> 浏览量+1 -> 查相关新闻 -> 组装响应
# 2. 业务规则：判断"可以 / 不可以"，失败时 raise HTTPException
#    例：用户名已存在、旧密码错误、未收藏不允许删除
# 3. 技术策略：缓存策略、分页换算、has_more 计算等与业务相关但非 SQL 的决策
#
# 边界约束：
# - 禁止直接写 SQL，一律通过 crud 层访问数据库
# - 不处理 HTTP 参数解析（那是 routers 的职责）
# - 不直接构造响应体（由 routers 统一调 success_response 包装）
#
# 模块清单：
# - auth.py      认证业务：密码校验、token 签发与解析（一人一 token）
# - users.py     用户业务：注册/登录编排、资料更新、改密码
# - news.py      新闻业务：旁路缓存策略、详情页多步编排
# - favorite.py  收藏业务：增删查清 + 业务规则
# - history.py   浏览历史业务：增删查清 + 业务规则
